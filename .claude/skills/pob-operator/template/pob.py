"""Headless Path of Building, driven against the installed GUI copy.

There is no second checkout: this boots the same files the desktop app runs, so
PoB's own auto-updater is the only thing that ever needs updating.

Nothing is written into the installation except the timeless-jewel .bin caches
the GUI generates for itself anyway -- and only when one is missing. Those are
built here with zlib (verified byte-identical to PoB's own output) because the
headless host has no Inflate(). The installation's own manifest.xml SHA-1s can
be used to confirm no file PoB owns is ever modified.

The boot file is generated by make_boot.py; see its docstring for what it
changes and why.
"""
import ctypes
import os
import re
import sys
import zlib

def find_install():
    """Locate the installed PoB Community (POE1).

    Order: the POB_INSTALL environment variable, the default %APPDATA% location,
    then the uninstall registry. Returns the default path if nothing is found,
    so PoB() raises a clear "no PoB installation at ..." instead of a vague one.
    """
    default = os.path.join(os.environ.get("APPDATA", ""), "Path of Building Community")

    override = os.environ.get("POB_INSTALL")
    if override and os.path.isfile(os.path.join(override, "Launch.lua")):
        return override
    if os.path.isfile(os.path.join(default, "Launch.lua")):
        return default

    try:
        import winreg
    except ImportError:
        return default
    roots = (
        (winreg.HKEY_CURRENT_USER, r"SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall"),
        (winreg.HKEY_LOCAL_MACHINE, r"SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall"),
        (winreg.HKEY_LOCAL_MACHINE,
         r"SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall"),
    )
    for hive, path in roots:
        try:
            key = winreg.OpenKey(hive, path)
        except OSError:
            continue
        with key:
            for i in range(winreg.QueryInfoKey(key)[0]):
                try:
                    with winreg.OpenKey(key, winreg.EnumKey(key, i)) as sub:
                        name = winreg.QueryValueEx(sub, "DisplayName")[0]
                        # skip the PoE2 build, which installs alongside
                        if name != "Path of Building Community":
                            continue
                        loc = winreg.QueryValueEx(sub, "InstallLocation")[0].strip('"')
                except OSError:
                    continue
                if loc and os.path.isfile(os.path.join(loc, "Launch.lua")):
                    return loc
    return default


INSTALL = find_install()
BOOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "headless_boot.lua")

LUA_MULTRET = -1


def inflate(data):
    """PoB's build codes and data blobs are zlib; tolerate the other framings."""
    for wbits in (15, -15, 31):
        try:
            return zlib.decompress(data, wbits)
        except zlib.error:
            continue
    raise ValueError("not a zlib/deflate/gzip stream")


def decode_import_code(code):
    """PoB / poe.ninja / pobb.in share code -> the build XML."""
    import base64
    code = code.strip().replace("-", "+").replace("_", "/")
    code += "=" * (-len(code) % 4)
    return inflate(base64.b64decode(code)).decode("utf-8", "replace")


def encode_import_code(xml):
    import base64
    raw = zlib.compress(xml.encode("utf-8") if isinstance(xml, str) else xml)
    return base64.b64encode(raw).decode("ascii").replace("+", "-").replace("/", "_")


class LuaError(RuntimeError):
    pass


def install_version(install=INSTALL):
    """The installed PoB version, from its manifest.xml."""
    try:
        text = open(os.path.join(install, "manifest.xml"), encoding="utf-8").read()
    except OSError:
        return None
    m = re.search(r'<Version number="([^"]+)"', text)
    return m.group(1) if m else None


def build_jewel_caches(install=INSTALL, verbose=True):
    """Make sure every compressed jewel archive has a non-empty .bin beside it.

    Mirrors DataJewelFileLoader: a single <name>.zip, or <name>.zip.part0..N
    concatenated. Existing non-empty caches are left alone.
    """
    data_dir = os.path.join(install, "Data", "TimelessJewelData")
    if not os.path.isdir(data_dir):
        return []
    names = set()
    for entry in os.listdir(data_dir):
        if entry.endswith(".zip"):
            names.add(entry[:-4])
        elif ".zip.part" in entry:
            names.add(entry.split(".zip.part")[0])

    built = []
    for name in sorted(names):
        bin_path = os.path.join(data_dir, name + ".bin")
        if os.path.exists(bin_path) and os.path.getsize(bin_path) > 0:
            continue
        blob = b""
        single = os.path.join(data_dir, name + ".zip")
        if os.path.exists(single):
            blob = open(single, "rb").read()
        else:
            part = 0
            while True:
                p = os.path.join(data_dir, "%s.zip.part%d" % (name, part))
                if not os.path.exists(p):
                    break
                blob += open(p, "rb").read()
                part += 1
        if not blob:
            continue
        with open(bin_path, "wb") as fh:
            fh.write(zlib.decompress(blob))
        built.append(name)
        if verbose:
            print("  built jewel cache: %s.bin" % name, file=sys.stderr)
    return built


class PoB:
    def __init__(self, install=INSTALL, boot=BOOT):
        if not os.path.isfile(os.path.join(install, "Launch.lua")):
            raise RuntimeError("no PoB installation at %s" % install)
        if not os.path.isfile(boot):
            raise RuntimeError("missing %s -- run make_boot.py" % boot)
        self.install = install

        build_jewel_caches(install)

        os.add_dll_directory(install)
        self.lua = ctypes.CDLL(os.path.join(install, "lua51.dll"))
        self._bind()

        self.L = self.lua.luaL_newstate()
        if not self.L:
            raise RuntimeError("luaL_newstate failed")
        self.lua.luaL_openlibs(self.L)

        # PoB resolves Launch.lua, Data/, TreeData/ against the cwd. The boot
        # file itself stays outside the installation and is loaded by absolute
        # path, so nothing has to be added to the install directory.
        self._prev_cwd = os.getcwd()
        os.chdir(install)
        inst = install.replace("\\", "/")
        self.eval(
            "package.path = '{i}/?.lua;{i}/lua/?.lua;{i}/lua/?/init.lua;' .. package.path\n"
            "package.cpath = '{i}/?.dll;' .. package.cpath\n"
            # a real interpreter would have set this; Main.lua indexes it
            "arg = arg or {{}}".format(i=inst)
        )
        self.run_file(boot)

    def load_build_code(self, code):
        """Load a build from a PoB import code (poe.ninja, pobb.in, forums)."""
        xml = decode_import_code(code)
        eq = "="
        while "]" + eq + "]" in xml:
            eq += "="
        self.eval('loadBuildFromXML([{eq}[{xml}]{eq}], "Imported")'.format(
            eq=eq, xml=xml))
        self.recalc()
        return xml

    def export_code(self):
        """The build's PoB share code.

        PoB's own encoder needs Deflate(), which is not available headless, so
        we take the XML from its serialiser and compress it here instead.
        """
        return encode_import_code(self.eval("return build:SaveDB('code')"))

    def _bind(self):
        lua, p = self.lua, ctypes.c_void_p
        lua.luaL_newstate.restype = p
        lua.luaL_openlibs.argtypes = [p]
        lua.luaL_loadstring.argtypes = [p, ctypes.c_char_p]
        lua.luaL_loadstring.restype = ctypes.c_int
        lua.luaL_loadfile.argtypes = [p, ctypes.c_char_p]
        lua.luaL_loadfile.restype = ctypes.c_int
        lua.lua_pcall.argtypes = [p, ctypes.c_int, ctypes.c_int, ctypes.c_int]
        lua.lua_pcall.restype = ctypes.c_int
        lua.lua_tolstring.argtypes = [p, ctypes.c_int, ctypes.POINTER(ctypes.c_size_t)]
        # a raw pointer, NOT c_char_p: that would decode to bytes truncated at
        # the first NUL, and compressed payloads are full of them
        lua.lua_tolstring.restype = ctypes.c_void_p
        lua.lua_settop.argtypes = [p, ctypes.c_int]
        lua.lua_gettop.argtypes = [p]
        lua.lua_gettop.restype = ctypes.c_int

    def _tostring(self, idx=-1):
        n = ctypes.c_size_t()
        s = self.lua.lua_tolstring(self.L, idx, ctypes.byref(n))
        return ctypes.string_at(s, n.value).decode("utf-8", "replace") if s else None

    def _call(self, rc, what):
        if rc != 0:
            msg = self._tostring()
            self.lua.lua_settop(self.L, 0)
            raise LuaError("load %s: %s" % (what, msg))
        rc = self.lua.lua_pcall(self.L, 0, LUA_MULTRET, 0)
        if rc != 0:
            msg = self._tostring()
            self.lua.lua_settop(self.L, 0)
            raise LuaError("run %s: %s" % (what, msg))
        out = self._tostring() if self.lua.lua_gettop(self.L) > 0 else None
        self.lua.lua_settop(self.L, 0)
        return out

    def run_file(self, path):
        return self._call(self.lua.luaL_loadfile(self.L, path.encode("utf-8")), path)

    def eval(self, chunk):
        """Run a Lua chunk; whatever it `return`s is coerced to a string."""
        return self._call(
            self.lua.luaL_loadstring(self.L, chunk.encode("utf-8")), "<chunk>")

    def load_build(self, xml_path):
        xml = open(xml_path, encoding="utf-8").read()
        # pass the XML through a Lua long-bracket literal to dodge escaping
        eq = "="
        while "]" + eq + "]" in xml:
            eq += "="
        name = os.path.splitext(os.path.basename(xml_path))[0].replace('"', "'")
        self.eval('loadBuildFromXML([{eq}[{xml}]{eq}], "{name}")'.format(
            eq=eq, xml=xml, name=name))
        self.recalc()

    def recalc(self):
        self.eval("build.buildFlag = true; runCallback('OnFrame')")

    def close(self):
        try:
            os.chdir(self._prev_cwd)
        except OSError:
            pass


